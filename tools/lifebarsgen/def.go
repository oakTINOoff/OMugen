	d.line("callfight.time = 56") // FIGHT! slams in as ROUND fades
	d.line("fight.time = 0")
	d.line("fight.anim = 520")
	d.line("fight.bg0.anim = 592")
	d.line("fight.snd = 1,0")
	d.line("fight.sndtime = 0")

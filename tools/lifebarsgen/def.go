package main

// fight.def and the font definitions. Player 1's elements are laid out from
// the constants in main.go; player 2's mirror them (facing = -1).

import (
	"fmt"
	"strings"
)

type def struct{ strings.Builder }

func (d *def) line(format string, a ...interface{}) { fmt.Fprintf(&d.Builder, format+"\n", a...) }

func (d *def) section(name, comment string) {
	d.line("")
	if comment != "" {
		d.line(";%s", comment)
	}
	d.line("[%s]", name)
}

// mirrorX is player 2's x for player 1's x.
func mirrorX(x int) int { return W - x }

// side keys: p is the player number (1-4), left says which side of the
// screen it is on.
func facing(d *def, key string, left bool) {
	if !left {
		d.line("%s.facing = -1", key)
	}
}

// lifebar writes one player's life bar at (x, y) with an optional scale for
// team partners.
func lifebar(d *def, p int, left bool, x, y int, scale float64) {
	pre := fmt.Sprintf("p%d.", p)
	side := 0
	if !left {
		side = 1
	}
	d.line("%spos = %d,%d", pre, x, y)
	el := func(name string, g, n int) {
		d.line("%s%s.spr = %d,%d", pre, name, g, n)
		facing(d, pre+name, left)
		if scale != 1 {
			d.line("%s%s.scale = %.2f,%.2f", pre, name, scale, scale)
		}
	}
	el("bg0", 10, side)
	el("mid", 12, 0)
	el("front100", 13, 0)
	el("front50", 13, 1)
	el("front25", 13, 2)
	el("front", 13, 3)
	d.line("%sfront.palfx.sinadd = 40,0,0,24", pre)
	el("top", 11, 0)
	reach := int(float64(int(life.l+life.slant+life.pad)) * scale)
	if left {
		d.line("%srange.x = %d,%d", pre, -int(life.pad), reach)
	} else {
		d.line("%srange.x = %d,%d", pre, int(life.pad), -reach)
	}
	d.line("%sscalefill = 1", pre)
}

func powerbar(d *def, p int, left bool) {
	pre := fmt.Sprintf("p%d.", p)
	side, x := 0, powerX
	if !left {
		side, x = 1, mirrorX(powerX)
	}
	d.line("%spos = %d,%d", pre, x, powerY)
	el := func(name string, g, n int) {
		d.line("%s%s.spr = %d,%d", pre, name, g, n)
		facing(d, pre+name, left)
	}
	el("bg0", 20, side)
	el("mid", 22, 0)
	el("front", 23, side)
	d.line("%sfront1000.spr = 23,%d", pre, side)
	facing(d, pre+"front1000", left)
	d.line("%sfront1000.palfx.add = 40,40,40", pre)
	el("top", 21, 0)
	reach := int(power.l + power.slant + power.pad)
	if left {
		d.line("%srange.x = %d,%d", pre, -int(power.pad), reach)
	} else {
		d.line("%srange.x = %d,%d", pre, int(power.pad), -reach)
	}
	d.line("%sscalefill = 1", pre)
	d.line("%slevelbars = 1", pre)
	// The level, in a badge at the outer end.
	align, off := 1, -20
	if !left {
		align, off = -1, 20
	}
	d.line("%scounter.offset = %d,%d", pre, off, 21)
	d.line("%scounter.font = 4,0,%d", pre, align)
}

func faceElems(d *def, p int, left bool, x, y int, scale float64) {
	pre := fmt.Sprintf("p%d.", p)
	side := 0
	if !left {
		side = 1
	}
	d.line("%spos = %d,%d", pre, x, y)
	el := func(name string, g, n int) {
		d.line("%s%s.spr = %d,%d", pre, name, g, n)
		facing(d, pre+name, left)
		if scale != 1 {
			d.line("%s%s.scale = %.2f,%.2f", pre, name, scale, scale)
		}
	}
	el("bg", 30, side)
	d.line("%sface.spr = 9000,0", pre)
	facing(d, pre+"face", left)
	if scale != 1 {
		d.line("%sface.scale = %.2f,%.2f", pre, scale, scale)
	}
	s := int(face.s * scale)
	x0 := x
	if !left {
		x0 = x - s
	}
	d.line("%sface.window = %d,%d, %d,%d", pre, x0, y, x0+s, y+s)
	el("top", 31, side)
}

func nameElem(d *def, p int, left bool, x, y int, font int) {
	pre := fmt.Sprintf("p%d.", p)
	align := 1
	if !left {
		align = -1
	}
	d.line("%spos = %d,%d", pre, x, y)
	d.line("%sname.font = %d,0,%d", pre, font, align)
}

// sides4 lays out a section for players 1-4 (odd players on the left).
func sides4(d *def, n int, f func(p int, left bool, partner bool)) {
	for p := 1; p <= n; p++ {
		f(p, p%2 == 1, p > 2)
	}
}

// anim writes an announcement: it slams in from big, holds, then fades.
func announceAnim(d *def, no, g, n, hold int) {
	d.section(fmt.Sprintf("Begin Action %d", no), "")
	for _, s := range []float64{1.7, 1.35, 1.15, 1.04} {
		d.line("%d,%d, 0,0, 2, , , %.2f,%.2f", g, n, s, s)
	}
	d.line("%d,%d, 0,0, %d", g, n, hold)
	d.line("%d,%d, 0,0, 3, , AS160D96", g, n)
	d.line("%d,%d, 0,0, 3, , AS80D176", g, n)
	d.line("%d,%d, 0,0, 3, , AS32D224", g, n)
}

// slashAnim is the streak behind an announcement: it stretches out, then
// fades.
func slashAnim(d *def, no, n, hold int) {
	d.section(fmt.Sprintf("Begin Action %d", no), "")
	for _, s := range []float64{0.2, 0.55, 0.85, 1} {
		d.line("590,%d, 0,0, 2, , A, %.2f,1", n, s)
	}
	d.line("590,%d, 0,0, %d, , A", n, hold)
	d.line("590,%d, 0,0, 3, , AS160D256", n)
	d.line("590,%d, 0,0, 3, , AS64D256", n)
}

